import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createPresenterTake, buildTakeFiles, zipTakeFiles } from '../js/presenter_take.js';
let time = 1000;
const log = createPresenterTake({ now: () => time, date: () => new Date('2026-09-24T12:00:00Z'), id: () => '12345678' });
const bundle = { script: 'Opening. Evidence. Conclusion.', presentation: { version: 1 }, validation: { status: 'passed' }, compiled: { title: 'Test', steps: [{ id: 'evidence', label: 'EVIDENCE', rationale: 'Read the figure.', edit: { shot: 'screen', reason: 'The figure supports this explanation.' } }], cues: [{ stepId: 'evidence', label: 'EVIDENCE', offset: 9 }] } };
log.begin(bundle, { width: 1920, height: 1080 });
time = 5000; log.sync();
time = 6000; log.record({ type: 'requested', stepId: 'evidence', label: 'EVIDENCE', direction: 'forward', navigationId: 1 });
time = 6700; log.record({ type: 'arrived', stepId: 'evidence', label: 'EVIDENCE', direction: 'forward', navigationId: 1 });
time = 7200; log.record({ type: 'retake', label: '=HYPERLINK("invalid")' });
time = 7500; log.record({ type: 'failed', navigationId: 2, error: 'Unavailable target' });
time = 8000; log.record({ type: 'arrived', stepId: 'evidence', label: 'EVIDENCE', direction: 'backward', navigationId: 3 });
assert.throws(() => buildTakeFiles(log.snapshot()), /Finish/);
time = 9500; log.end();
const take = log.snapshot();
assert.equal(take.events[1].elapsedMs, 1000);
assert.equal(take.events[2].elapsedMs, 1700);
assert.equal(take.events.at(-1).elapsedMs, 4500);
assert.equal(take.status, 'completed');
assert.equal(take.capture.verifiedByApp, false);
log.record({ type: 'arrived' }); assert.equal(log.snapshot().events.length, take.events.length);
assert.throws(() => log.begin(bundle, {}), /Download/);
const files = buildTakeFiles(take);
assert.match(files['script-timed.md'], /00:00:01.700 forward; 00:00:03.000 backward/);
assert.match(files['edit-guide.md'], /Unavailable target/);
assert.match(files['cues.csv'], /'=HYPERLINK/);
assert.match(files['edit-guide.md'], /not an automatic Resolve import/);
const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'planeir-take-'));
try {
  const zip = path.join(directory, 'take.zip'); await fs.writeFile(zip, Buffer.from(await zipTakeFiles(files).arrayBuffer()));
  execFileSync('/usr/bin/unzip', ['-t', zip]);
  assert.equal(execFileSync('/usr/bin/unzip', ['-p', zip, 'script.md'], { encoding: 'utf8' }), bundle.script);
} finally { await fs.rm(directory, { recursive: true, force: true }); }
log.exported(); log.begin(bundle, {}); log.sync();
const recovered = createPresenterTake(); recovered.restore(log.snapshot());
assert.equal(recovered.snapshot().status, 'interrupted'); assert.equal(recovered.active, false);
assert.match(buildTakeFiles(recovered.snapshot())['edit-guide.md'], /Page reloaded/);
const cancelled = createPresenterTake(); cancelled.begin(bundle, {}); cancelled.end('exit');
assert.equal(cancelled.snapshot().status, 'cancelled'); assert.equal(cancelled.snapshot().events.length, 0);
console.log('Take log passed: monotonic sync offsets, arrivals vs requests, repeats/failures, interrupted recovery, export guard, CSV safety and ZIP integrity.');
