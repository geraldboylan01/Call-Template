import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const promptDir = resolve(root, 'docs/prompt-pack');
const masterPath = resolve(promptDir, 'MASTER_PROJECT_PROMPT.md');
const outputPath = resolve(root, 'js/planning/playbook_manifest.generated.js');
const marker = /<!--\s*planeir-planning-module\s+(\{[^\n]+\})\s*-->/g;

function entriesFrom(source, label) {
  return [...source.matchAll(marker)].map((match) => {
    let entry;
    try {
      entry = JSON.parse(match[1]);
    } catch (_error) {
      throw new Error(`${label} contains invalid planning-module metadata.`);
    }
    if (!/^[a-z][a-z0-9_]{1,79}$/.test(entry.moduleId)
      || !/^generated\.[A-Za-z][A-Za-z0-9]*$/.test(entry.outputKey)
      || entry.role !== 'analysis') {
      throw new Error(`${label} contains invalid planning-module fields for ${entry.moduleId || 'unknown'}.`);
    }
    return Object.freeze({
      moduleId: entry.moduleId,
      outputKey: entry.outputKey,
      role: entry.role,
      source: label
    });
  });
}

const componentFiles = readdirSync(promptDir)
  .filter((name) => /^\d{2}_.+_playbook\.md$/.test(name))
  .sort();
const componentSources = componentFiles.map((name) => ({
  name,
  text: readFileSync(resolve(promptDir, name), 'utf8')
}));
const componentEntries = componentSources.flatMap(({ name, text }) => entriesFrom(text, name));
const masterEntries = entriesFrom(readFileSync(masterPath, 'utf8'), 'MASTER_PROJECT_PROMPT.md');
const duplicateIds = componentEntries
  .map((entry) => entry.moduleId)
  .filter((id, index, all) => all.indexOf(id) !== index);
if (duplicateIds.length) throw new Error(`Duplicate planning module metadata: ${[...new Set(duplicateIds)].join(', ')}`);

const byModuleId = (left, right) => left.moduleId.localeCompare(right.moduleId);
const canonical = componentEntries.map(({ source: _source, ...entry }) => entry).sort(byModuleId);
const masterCanonical = masterEntries.map(({ source: _source, ...entry }) => entry).sort(byModuleId);
if (JSON.stringify(masterCanonical) !== JSON.stringify(canonical)) {
  throw new Error('MASTER_PROJECT_PROMPT.md planning-module metadata is out of sync with component playbooks.');
}

const guidance = Object.fromEntries(componentSources.flatMap(({ name, text }) => (
  entriesFrom(text, name).map((entry) => [entry.moduleId, text.trim()])
)).sort(([left], [right]) => left.localeCompare(right)));

const source = `/* Generated by scripts/generate-planning-playbook-manifest.mjs. Do not edit. */\n`
  + `export const PLANNING_PLAYBOOK_MANIFEST_VERSION = 'planning-playbooks-1.0.0';\n\n`
  + `export const PLANNING_PLAYBOOK_MANIFEST = Object.freeze(${JSON.stringify(canonical, null, 2)}.map(Object.freeze));\n\n`
  + `export const PLANNING_PLAYBOOK_GUIDANCE = Object.freeze(${JSON.stringify(guidance, null, 2)});\n`;

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== source) throw new Error('Generated planning playbook manifest is stale.');
  console.info(`[PlanningPlaybooks] ${canonical.length} master-prompt analysis templates are in sync.`);
} else {
  writeFileSync(outputPath, source);
  console.info(`[PlanningPlaybooks] wrote ${canonical.length} entries to ${outputPath}.`);
}
